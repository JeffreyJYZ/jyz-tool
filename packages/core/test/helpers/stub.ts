/**
 * Cross-platform stub executables for tests.
 *
 * A test stub used to be a `#!/bin/sh` script, which cannot run on Windows: there the shell does not
 * exist and an extensionless file is not executable. So the launcher is written per platform — a
 * shell script on POSIX, a `.cmd` shim on Windows — and both hand off to one Bun script that does the
 * recording. That keeps the recorded output byte-identical on every platform, which is what the
 * assertions compare, and it still proves nothing outside the stub was reached: the Bun script is
 * the only thing the launcher runs.
 */

import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface StubOptions {
	/** Append every argument, one line per call, to this file. */
	record?: string;
	/** Append the stub's own name to this file, once per call. */
	marker?: string;
	/** Exit code the stub returns. */
	exitCode?: number;
	/** `simple` writes `$*`; `block` writes `cmd= cwd= arg= --` lines, one block per call. */
	format?: "simple" | "block";
	/**
	 * Behaviour the stub runs after recording, as source for a function over `string[]` returning
	 * `{ stdout?, stderr?, exitCode? }`. A string rather than a function because the runner is
	 * written to disk and executed by Bun; a function's `toString()` works for arrow bodies only.
	 */
	behaviour?: string;
}

const RUNNER = (name: string, options: StubOptions): string => {
	const record = options.record ? JSON.stringify(options.record) : "null";
	const marker = options.marker ? JSON.stringify(options.marker) : "null";
	const exitCode = options.exitCode ?? 0;
	const behaviour = options.behaviour ?? "null";
	return `// Generated by packages/core/test/helpers/stub.ts — records one call, then exits.
const record = ${record};
const marker = ${marker};
const format = ${JSON.stringify(options.format ?? "simple")};
const behaviour: ((argv: string[]) => { stdout?: string; stderr?: string; exitCode?: number }) | null = ${behaviour};
const exitCode = ${exitCode};
const lines: string[] = [];
if (format === "block") {
	lines.push(\`cmd=${name}\`);
	lines.push(\`cwd=\${process.cwd()}\`);
	for (const arg of process.argv.slice(2)) lines.push(\`arg=\${arg}\`);
	lines.push("--");
} else {
	lines.push(process.argv.slice(2).join(" "));
}
if (record !== null) {
	const file = Bun.file(record);
	const before = (await file.exists()) ? await file.text() : "";
	await Bun.write(record, before + lines.join("\\n") + "\\n");
}
if (marker !== null) {
	const file = Bun.file(marker);
	const before = (await file.exists()) ? await file.text() : "";
	await Bun.write(marker, \`\${before}${name}\\n\`);
}
const result = behaviour === null ? null : await behaviour(process.argv.slice(2));
if (result?.stdout !== undefined) process.stdout.write(result.stdout);
if (result?.stderr !== undefined) process.stderr.write(result.stderr);
process.exit(result?.exitCode ?? exitCode);
`;
};

/**
 * Write a stub named `name` into `dir` and return the path a caller should spawn. On Windows that is
 * `dir/name.cmd`, which the OS finds by name on PATH; elsewhere it is `dir/name`.
 */
export function writeStub(dir: string, name: string, options: StubOptions = {}): string {
	mkdirSync(dir, { recursive: true });
	const script = join(dir, `${name}.stub.ts`);
	writeFileSync(script, RUNNER(name, options), "utf8");

	if (process.platform === "win32") {
		const shim = join(dir, `${name}.cmd`);
		const body = [
			"@echo off",
			`"${process.execPath}" "${script}" %*`,
			`exit /b ${options.exitCode ?? 0}`,
		];
		writeFileSync(shim, `${body.join("\r\n")}\r\n`, "utf8");
		return shim;
	}
	const launcher = join(dir, name);
	// Absolute Bun: several tests replace PATH with only the stub directory, so a bare `bun` is
	// not found there on any platform.
	const body = ["#!/bin/sh", `exec "${process.execPath}" "${script}" "$@"`];
	writeFileSync(launcher, `${body.join("\n")}\n`, "utf8");
	chmodSync(launcher, 0o755);
	return launcher;
}

/** Write several stubs into one directory and return it, ready to prepend to PATH. */
export function writeStubs(dir: string, names: string[], options: StubOptions = {}): string {
	mkdirSync(dir, { recursive: true });
	for (const name of names) writeStub(dir, name, options);
	return dir;
}
